"""System files: the JSON model of a multi-FMU system, its checks, parameter layering, and the
``SystemSpec`` a system run records (ADR 0009).

A system file (version 1) is written by Claude with its own Write or Edit tool, or by
``system_import``. Example::

    {
      "version": 1,
      "components": {
        "PI":  {"fmu": "generated/PIController/PIController.fmu", "parameters": {"Kp": 10}},
        "MSD": {"fmu": "generated/MSD/MSD.fmu"}
      },
      "connections": [{"from": "PI.u", "to": "MSD.F"}, {"from": "MSD.x", "to": "PI.y"}],
      "experiment": {"start_time": 0, "stop_time": 10, "step_size": 0.01}
    }

Rules: unknown keys are refused; at most ``Limits.system_file_max_bytes``; component names
match ``protocol.COMPONENT_NAME_PATTERN`` and aren't Windows reserved names; a reference
``<component>.<variable>`` splits at the first dot; ``fmu`` paths are relative to the system
file's directory (or absolute) and must resolve, symlinks included, inside
``Config.allowed_roots``. There are no ``outputs``: ``run_start`` chooses them (default: every
component's recordable outputs). The communication step ``experiment.step_size`` is required:
OMSimulator couples Jacobi-style, so the step changes a closed loop's dynamics (spike (g)).
It also always starts at t = 0 and steps while ``t < stop - h/2`` (spike (h)), so ``start_time``
must be 0 and ``stop_time - start_time`` a whole number of steps.

Parameter layers, lowest precedence first: the FMU's own start values < the system file's
``parameters`` < the run's ``.ssv`` parameter set < ``start_values`` (keys
``<component>.<variable>``). ``SystemSpec.parameters`` records each winning value with its
layer, converted to the variable's type (a Real gets ``10.0`` for ``10``, because OMSimulator's
``setValue`` picks the setter from the Python type). Only parameters, inputs no connection
drives, and states with ``initial`` exact or approx can be set; never outputs, calculated or
structural parameters, constants or array variables.

Checks reuse ``fmu/inspect.py`` (``read_description``, ``platform_blocker``, close matches in
the style of ``require_variables``); nothing here loads a binary or imports OMSimulator. The
two things read besides ``modelDescription.xml`` are the zip directory (``platform_blocker``)
and ``resources/slavemodule.txt`` of pythonfmu FMUs. :func:`plan_run` hashes each distinct FMU
once, for the ``FmuRef`` in the spec.

Collaborators: ``config`` (roots, limits), ``fmu/inspect.py``, ``fmu/catalog.py`` (path
resolution), ``budget.py`` (the ``system_check`` result is cut to the JSON budget),
``store/protocol.py`` (``SystemSpec`` and its parts), ``runs.py`` (``run_start(system=...)``
calls :func:`load_system` and :func:`plan_run` after the pin check of ``oms_pin``), ``ssp.py``
(imports and exports system files; reads parameter sets into :class:`Paramset`),
``mcp/server.py`` (``system_check``).
"""

