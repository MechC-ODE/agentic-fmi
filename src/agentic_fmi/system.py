class _Strict(BaseModel):
    """Base of the system file models: unknown keys are errors, floats must be finite."""

    model_config = ConfigDict(extra="forbid", frozen=True, allow_inf_nan=False)


class SystemComponent(_Strict):
    """One component: an FMU and the parameter values the system gives it."""

    fmu: str = Field(
        min_length=1,
        description="FMU path, relative to the system file's directory (or absolute), inside "
        "the workspace.",
    )
    parameters: dict[str, StartValue] = Field(
        default_factory=dict,
        description="Start values by variable name (parameters, inputs not driven by a "
        "connection, or states with initial exact or approx).",
    )


class Connection(SystemConnection):
    """``{"from": "<component>.<output>", "to": "<component>.<input>"}``."""

    model_config = ConfigDict(extra="forbid")


class SystemExperiment(_Strict):
    """The system's experiment; ``run_start`` may override each field."""

    start_time: FiniteFloat = 0.0
    stop_time: FiniteFloat
    step_size: FiniteFloat = Field(
        gt=0,
        description="Communication step h in seconds; one result row per step. Choose it "
        "consciously: the Jacobi coupling adds up to a step of delay around a loop.",
    )

    @model_validator(mode="after")
    def _stop_after_start(self) -> SystemExperiment:
        if self.stop_time <= self.start_time:
            raise ValueError("stop_time must be greater than start_time")
        return self


class SystemFile(_Strict):
    """A system file, version 1 (ADR 0009)."""

    version: Literal[1]
    components: dict[ComponentName, SystemComponent] = Field(min_length=1)
    connections: list[Connection] = Field(default_factory=list)
    experiment: SystemExperiment


class SystemExperimentView(BaseModel):
    """The resolved experiment in a ``system_check`` result."""

    start_time: float
    stop_time: float
    step_size: float


class SystemCheck(BaseModel):
    """The ``system_check`` result. Problems are listed, not raised; each names where it is
    (``connections[1]``, ``PI.y``) and the fix."""

    system: str
    """Workspace-relative path of the system file."""
    ok: bool
    """No errors: ``run_start(system=...)`` will accept it."""
    components: dict[str, str]
    """Component -> workspace-relative FMU path."""
    connections: int
    experiment: SystemExperimentView | None = None
    errors: list[str] = []
    warnings: list[str] = []
    truncated: bool = False
    """True if problems were cut to fit the output budget."""


@dataclass(frozen=True)
class LoadedSystem:
    """A system file read once, parsed and resolved: what the checks and the run plan use."""

    path: Path
    """Absolute, symlink-resolved path of the system file."""
    ref: FileRef
    """Its path, sha256 and size: the bytes parsed are the bytes hashed."""
    name: str
    """The file's stem: the system's display name."""
    file: SystemFile
    fmus: Mapping[str, Path]
    """Component -> absolute, resolved FMU path (inside the allowed roots)."""
    descriptions: Mapping[str, ModelDescription]
    """Component -> parsed ``modelDescription.xml`` (one parse per distinct FMU file)."""


@dataclass(frozen=True)
class Paramset:
    """A ``.ssv`` parameter set as read by ``ssp.read_paramset`` (the same parser as
    ``system_import``): values keyed ``<component>.<variable>``, and the units it declares."""

    ref: FileRef
    values: Mapping[str, StartValue]
    units: Mapping[str, str]
    """Name -> ``unit`` attribute of its ``ssv:Real``, where given; a unit that differs from
    the variable's declared unit is an error (no unit conversion)."""


@dataclass(frozen=True)
class SystemPlan:
    """A validated system run request that becomes ``spec.json`` once it has a run ID."""

    loaded: LoadedSystem
    paramset: FileRef | None
    parameters: Mapping[str, ResolvedValue]
    start_time: float
    stop_time: float
    step_size: float
    outputs: Sequence[str]
    timeout_s: float
    estimated_steps: float
    force: bool
    fmu_refs: Mapping[str, FmuRef]
    """Component -> its FMU pinned by sha256 (hashed once, in :func:`plan_run`)."""
    omsimulator: OmsVersion
    """The installed OMSimulator identity the server checked against the pin."""
    live: bool = False
    """A live run (ADR 0010): the spec records ``live`` and ``idle_limit_s``."""
    idle_limit_s: float | None = None
    """``Timing.live_idle_limit_s`` for a live run, else ``None``."""

    def spec(self, run_id: str) -> SystemSpec:
        """The ``SystemSpec`` for ``run_id``: stamped now, with ``Versions.current()``, the FMU
        refs (path, sha256, size, FMI version, model name), the OMSimulator identity and, for a
        live run, ``live`` and ``idle_limit_s``."""
        return SystemSpec(
            run_id=run_id,
            created_at=utc_now(),
            name=self.loaded.name,
            system=self.loaded.ref,
            paramset=self.paramset,
            components={name: ComponentSpec(fmu=ref) for name, ref in self.fmu_refs.items()},
            connections=[
                SystemConnection.model_validate({"from": c.from_, "to": c.to})
                for c in self.loaded.file.connections
            ],
            parameters=dict(self.parameters),
            master=MasterAlgorithm(step_size=self.step_size),
            experiment=Experiment(
                start_time=self.start_time,
                stop_time=self.stop_time,
                output_interval=self.step_size,
            ),
            outputs=list(self.outputs),
            timeout_s=self.timeout_s,
            estimated_steps=self.estimated_steps,
            force=self.force,
            versions=Versions.current(),
            omsimulator=self.omsimulator,
            live=self.live,
            idle_limit_s=self.idle_limit_s,
        )


def is_reserved_name(name: str) -> bool:
    """Whether ``name`` is a file name Windows refuses (``CON``, ``COM1``, ``lpt3``, ...)."""
    return name.upper() in WINDOWS_RESERVED_NAMES


# --- loading ----------------------------------------------------------------------------------


def load_system(config: Config, system: str) -> LoadedSystem:
    """Read, hash and parse a system file, and resolve its FMU paths.

    Resolution as ``fmu/catalog.resolve_fmu`` (containment checked before existence, so an
    outside path is refused without revealing whether it exists), but relative FMU paths are
    taken against the system file's directory. Reads the file once (at most
    ``Limits.system_file_max_bytes``), hashes those bytes and validates them as
    :class:`SystemFile`; checks ``Limits.system_max_components`` and
    ``system_max_connections`` and Windows reserved component names. Parses each FMU's
    ``modelDescription.xml`` with ``fmu.inspect.read_description``.

    Raises:
        UserError: the file is missing, outside the roots, too large, not UTF-8 JSON, or not a
            valid version 1 system file (the first few validation errors with their JSON
            paths); an FMU path doesn't resolve or isn't readable. Each message names the fix.
    """
    path = _resolve_system_file(config, system)
    shown = relative_path(config, path)
    data = _read_bounded(path, config.limits.system_file_max_bytes, shown)
    file = _parse(data, shown)
    _check_counts(file, config.limits, shown)
    fmus = _resolve_fmus(config, path.parent, file)
    return LoadedSystem(
        path=path,
        ref=FileRef(path=str(path), sha256=hashlib.sha256(data).hexdigest(), size_bytes=len(data)),
        name=path.stem,
        file=file,
        fmus=fmus,
        descriptions=_read_descriptions(fmus),
    )


def _resolve_system_file(config: Config, system: str) -> Path:
    """The absolute, symlink-resolved path of an existing system file inside the allowed roots."""
    if not system or not system.strip():
        raise UserError(
            "The system argument is empty. Pass the workspace-relative path of a system file "
            "(JSON), for example 'systems/loop.json'."
        )
    candidate = Path(system)
    if not candidate.is_absolute():
        candidate = config.workspace / candidate
    try:
        resolved = candidate.resolve()
    except (OSError, RuntimeError, ValueError) as exc:
        raise UserError(f"Can't resolve the system path {system!r}: {exc}.") from exc
    if not any(resolved.is_relative_to(root) for root in config.allowed_roots):
        raise UserError(
            f"System file {system!r} is outside the workspace ({config.workspace}), possibly "
            "through a symlink. Put the system file inside the workspace."
        )
    if candidate.suffix.lower() == ".ssp":
        raise UserError(
            f"{system!r} is an SSP archive, not a system file. Convert it with "
            "system_import and use the imported/<name>/<name>.json it writes."
        )
    if resolved.is_dir():
        raise UserError(f"{system!r} is a directory. Pass the system file (JSON) itself.")
    if not resolved.is_file():
        raise UserError(
            f"System file {system!r} was not found in the workspace. Write it first (paths "
            "are relative to the workspace), then call system_check."
        )
    return resolved


def _read_bounded(path: Path, limit: int, shown: str) -> bytes:
    """The file's bytes, read once; at most ``limit`` of them."""
    try:
        with path.open("rb") as handle:
            data = handle.read(limit + 1)
    except OSError as exc:
        raise UserError(
            f"Can't read {shown}: {exc.strerror or exc}. Check the path and its permissions."
        ) from exc
    if len(data) > limit:
        raise UserError(
            f"{shown} is larger than {limit // 1024} KiB, the most a system file may be. "
            "Split the system, or remove what isn't needed."
        )
    return data


def _parse(data: bytes, shown: str) -> SystemFile:
    """The bytes as a version 1 system file."""
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        raise UserError(f"{shown} is not UTF-8 text. Save the system file as UTF-8 JSON.") from exc
    try:
        return SystemFile.model_validate_json(text)
    except ValidationError as exc:
        found = exc.errors(include_url=False, include_input=False)
        listed = "; ".join(_validation_text(error) for error in found[:MAX_REFUSAL_ERRORS])
        more = f" ({len(found)} problems in all)" if len(found) > MAX_REFUSAL_ERRORS else ""
        raise UserError(
            f"{shown} is not a valid version 1 system file{more}: {listed}. Fix these, then "
            "call system_check again; the system_check description shows the format."
        ) from exc


def _validation_text(error: Mapping[str, Any]) -> str:
    """One pydantic error as ``where: what is wrong``."""
    location = [str(part) for part in error["loc"]]
    where = ".".join(part for part in location if part != "[key]") or "the file"
    kind = error["type"]
    if kind == "string_pattern_mismatch" and location[-1] in ("from", "to"):
        return (
            f"{where} must look like '<component>.<variable>' (a component name, a dot, the "
            "variable name), e.g. 'PI.u'"
        )
    if kind == "string_pattern_mismatch" and "[key]" in location:
        return (
            f"{where} is not a valid component name (letters, digits and underscores, not "
            "starting with a digit, at most 64 characters)"
        )
    message = str(error["msg"]).removeprefix("Value error, ")
    return f"{where}: {message}"


def _check_counts(file: SystemFile, limits: Limits, shown: str) -> None:
    """Refuse too many components or connections, and Windows reserved component names."""
    if len(file.components) > limits.system_max_components:
        raise UserError(
            f"{shown} has {len(file.components)} components; the limit is "
            f"{limits.system_max_components}. Split the system."
        )
    if len(file.connections) > limits.system_max_connections:
        raise UserError(
            f"{shown} has {len(file.connections)} connections; the limit is "
            f"{limits.system_max_connections}. Split the system."
        )
    for name in file.components:
        if is_reserved_name(name):
            raise UserError(
                f"Component name {name!r} is a reserved file name on Windows (the component "
                f"becomes {name}.fmu). Rename the component."
            )


def _resolve_fmus(config: Config, base: Path, file: SystemFile) -> dict[str, Path]:
    """Each component's FMU, resolved against the system file's directory."""
    fmus: dict[str, Path] = {}
    for name, component in file.components.items():
        try:
            fmus[name] = resolve_fmu(config, str(base / component.fmu))
        except UserError as exc:
            raise UserError(f"components.{name}.fmu ({component.fmu!r}): {exc}") from exc
    return fmus


def _read_descriptions(fmus: Mapping[str, Path]) -> dict[str, ModelDescription]:
    """Each component's ``modelDescription.xml``, parsed once per distinct FMU file."""
    parsed: dict[Path, ModelDescription] = {}
    descriptions: dict[str, ModelDescription] = {}
    for name, path in fmus.items():
        if path not in parsed:
            try:
                parsed[path] = read_description(path)
            except UserError as exc:
                raise UserError(f"components.{name}: {exc}") from exc
        descriptions[name] = parsed[path]
    return descriptions


# --- variable lookup ----------------------------------------------------------------------------


@dataclass(frozen=True)
class _Index:
    """Every component's variables by name: the lookups of the checks and the layers."""

    loaded: LoadedSystem
    variables: Mapping[str, Mapping[str, Any]]

    @classmethod
    def of(cls, loaded: LoadedSystem) -> _Index:
        return cls(
            loaded,
            {
                name: {variable.name: variable for variable in md.modelVariables}
                for name, md in loaded.descriptions.items()
            },
        )


def _close(word: str, options: Iterable[str]) -> str:
    """`` Close matches: a, b.`` (with a leading space), or nothing."""
    close = difflib.get_close_matches(word, list(options), n=MAX_CLOSE_MATCHES)
    return f" Close matches: {', '.join(close)}." if close else ""


def _variable(index: _Index, ref: str) -> Any:
    """The scalar variable ``<component>.<variable>`` names.

    Raises:
        ValueError: the reference is malformed or names nothing; the text has the fix.
    """
    component, dot, name = ref.partition(".")
    if not dot:
        raise ValueError(
            f"{ref!r} is not '<component>.<variable>'. Write the component name, a dot, then "
            "the variable name, e.g. 'PI.u'."
        )
    variables = index.variables.get(component)
    if variables is None:
        names = list(index.variables)[:MAX_LISTED_COMPONENTS]
        raise ValueError(
            f"unknown component {component!r}.{_close(component, index.variables)} "
            f"Components: {', '.join(names)}."
        )
    variable = variables.get(name)
    if variable is None:
        fmu = index.loaded.fmus[component].name
        raise ValueError(
            f"component {component} ({fmu}) has no variable {name!r}.{_close(name, variables)} "
            "Call fmu_variables on that FMU to list its names."
        )
    if variable.dimensions:
        raise ValueError(
            f"{ref} is an array variable; systems connect, set and record scalar variables. "
            "Use a scalar variable."
        )
    return variable


def _unit_of(variable: Any) -> str | None:
    """The variable's declared unit: its own, else its declared type's."""
    own = getattr(variable, "unit", None)
    if own:
        return str(own)
    declared = getattr(variable, "declaredType", None)
    inherited = getattr(declared, "unit", None)
    return str(inherited) if inherited else None


def _components_by_path(loaded: LoadedSystem) -> dict[Path, list[str]]:
    """The components of each distinct FMU file, in system-file order."""
    by_path: dict[Path, list[str]] = defaultdict(list)
    for name, path in loaded.fmus.items():
        by_path[path].append(name)
    return by_path


def _digest(path: Path) -> str:
    """The file's sha256, or its path as a stand-in if it can't be read."""
    try:
        return sha256_file(path)
    except OSError:
        return str(path)


# --- checks -----------------------------------------------------------------------------------


def problems(loaded: LoadedSystem, limits: Limits) -> tuple[list[str], list[str]]:
    """The errors and warnings of a loaded system (guardrails of ADR 0009).

    Errors, each with a fix: unknown component or variable (close matches); ``from`` not an
    output or ``to`` not an input; an input with more than one driver; incompatible types
    (families float, integer, boolean and enumeration must match; String, Binary and Clock are
    refused); declared units that differ (both sides declare one); a component without
    Co-Simulation, or without a binary for this platform, or ScheduledExecution only; two
    components of one FMU that declares ``canBeInstantiatedOnlyOncePerProcess``; two pythonfmu
    FMUs with different sha256 but the same slave module (``resources/slavemodule.txt``), which
    would share one imported module in the worker; a system-file parameter that is unknown, of
    the wrong type, constant, a calculated parameter, or an input driven by a connection; an
    experiment OMSimulator can't run: a start time other than 0 (it always starts its clock
    there), a step above the horizon, or a horizon that is not a whole number of steps (it steps
    while ``t < stop - h/2``, so the run would end early or late; the message names the nearest
    step that divides it).

    Warnings: a unit on one side of a connection only; inputs left unconnected (they keep
    their start values).
    """
    errors, warnings = _structure_problems(loaded)
    errors.extend(_experiment_problems(loaded.file.experiment))
    return _clipped(errors, limits), _clipped(warnings, limits)


def _structure_problems(loaded: LoadedSystem) -> tuple[list[str], list[str]]:
    """:func:`problems` without the experiment check (``plan_run`` checks the effective one)."""
    index = _Index.of(loaded)
    drivers = _drivers(index)
    connection_errors, warnings = _connection_problems(index)
    errors = _component_problems(loaded)
    errors.extend(connection_errors)
    errors.extend(_driver_problems(drivers))
    errors.extend(_parameter_problems(index, drivers))
    warnings.extend(_unconnected_warnings(index, drivers))
    return errors, warnings


def _clipped(messages: list[str], limits: Limits) -> list[str]:
    return [truncate(message, limits.message_max_chars) for message in messages]


def _component_problems(loaded: LoadedSystem) -> list[str]:
    """Components that can't run here, and FMUs that can't share a process."""
    errors: list[str] = []
    for name, path in loaded.fmus.items():
        problem = _cannot_run(path, loaded.descriptions[name])
        if problem is not None:
            errors.append(f"components.{name}: {path.name} can't run here: {problem}")
    errors.extend(_once_per_process_problems(loaded))
    errors.extend(_slave_module_problems(loaded))
    return errors


def _cannot_run(path: Path, md: ModelDescription) -> str | None:
    """Why this FMU can't be a system component on this machine, or ``None``."""
    if md.coSimulation is None:
        if md.modelExchange is None:
            return (
                "it declares ScheduledExecution only. Systems couple Co-Simulation FMUs; "
                "export the model as Co-Simulation."
            )
        return (
            "it has no Co-Simulation interface (ModelExchange only). Systems couple "
            "Co-Simulation FMUs; export the model with a Co-Simulation interface."
        )
    if md.fmiVersion not in ("2.0", "3.0"):
        return f"it declares FMI version {md.fmiVersion!r}; export the model as FMI 2.0 or 3.0."
    return platform_blocker(path, md)


def _once_per_process_problems(loaded: LoadedSystem) -> list[str]:
    """Two components instantiating an FMU that allows one instance per process."""
    groups: dict[str, list[str]] = defaultdict(list)
    for path, names in _components_by_path(loaded).items():
        interface = loaded.descriptions[names[0]].coSimulation
        if interface is not None and interface.canBeInstantiatedOnlyOncePerProcess:
            groups[_digest(path)].extend(names)
    return [
        f"components {', '.join(names)}: {loaded.fmus[names[0]].name} declares "
        "canBeInstantiatedOnlyOncePerProcess, but the worker runs every component in one "
        f"process and {len(names)} components instantiate it. Use one component of it, or an "
        "FMU that can be instantiated several times."
        for names in groups.values()
        if len(names) > 1
    ]


def _slave_module(path: Path) -> str | None:
    """The slave module a pythonfmu FMU imports (``resources/slavemodule.txt``), or ``None``."""
    try:
        with zipfile.ZipFile(path) as archive, archive.open(SLAVE_MODULE_MEMBER) as member:
            text = member.read(SLAVE_MODULE_MAX_BYTES).decode("utf-8").strip()
    except (KeyError, zipfile.BadZipFile, OSError, UnicodeDecodeError):
        return None
    return text or None


def _slave_module_problems(loaded: LoadedSystem) -> list[str]:
    """Different pythonfmu FMUs with one slave module name: the worker's interpreter imports a
    module once, so the second FMU would silently run the first one's code."""
    modules: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for path, names in _components_by_path(loaded).items():
        module = _slave_module(path)
        if module is not None:
            modules[module][_digest(path)].extend(names)
    errors: list[str] = []
    for module, variants in modules.items():
        if len(variants) < 2:
            continue
        who = "; ".join(
            f"{', '.join(names)} ({loaded.fmus[names[0]].name})" for names in variants.values()
        )
        errors.append(
            f"pythonfmu FMUs with the same slave module {module!r} but different content: "
            f"{who}. The worker imports every slave module into one interpreter, so the "
            "second FMU would run the first one's code. Rename one source file (its name is "
            "the module name) and rebuild that FMU with fmu_build."
        )
    return errors


def _connection_problems(index: _Index) -> tuple[list[str], list[str]]:
    """Per connection: unknown ends, direction, types and units."""
    errors: list[str] = []
    warnings: list[str] = []
    for i, connection in enumerate(index.loaded.file.connections):
        where = f"connections[{i}]"
        ends: dict[str, Any] = {}
        for side, ref in (("from", connection.from_), ("to", connection.to)):
            try:
                ends[side] = _variable(index, ref)
            except ValueError as exc:
                errors.append(f"{where}.{side} '{ref}': {exc}")
        if len(ends) == 2:
            found_errors, found_warnings = _pair_problems(
                where, connection, ends["from"], ends["to"]
            )
            errors.extend(found_errors)
            warnings.extend(found_warnings)
    return errors, warnings


def _pair_problems(
    where: str, connection: SystemConnection, source: Any, target: Any
) -> tuple[list[str], list[str]]:
    """Errors and warnings of one connection whose two ends exist."""
    origin, destination = connection.from_, connection.to
    direction = _direction_problems(where, origin, source, destination, target)
    if direction:
        return direction, []
    mismatch = _type_problem(where, origin, source, destination, target)
    if mismatch is not None:
        return [mismatch], []
    return _unit_problems(where, origin, source, destination, target)


def _direction_problems(
    where: str, origin: str, source: Any, destination: str, target: Any
) -> list[str]:
    """A connection starts at an output and ends at an input."""
    if source.causality == "input" and target.causality == "output":
        fix = json.dumps({"from": destination, "to": origin})
        return [
            f"{where}: from and to are swapped: {origin} is an input and {destination} is an "
            f"output. Write {fix}."
        ]
    errors: list[str] = []
    if source.causality != "output":
        errors.append(
            f"{where}.from: {origin} has causality '{source.causality}', but a connection "
            "starts at an output. Name an output (fmu_variables with causality='output' "
            "lists them)."
        )
    if target.causality != "input":
        errors.append(
            f"{where}.to: {destination} has causality '{target.causality}', but a connection "
            "ends at an input. Name an input (fmu_variables with causality='input' lists them)."
        )
    return errors


def _type_problem(
    where: str, origin: str, source: Any, destination: str, target: Any
) -> str | None:
    """Both ends must be a connectable type, of the same family."""
    for ref, variable in ((origin, source), (destination, target)):
        if variable.type not in TYPE_FAMILY:
            return (
                f"{where}: {ref} is a {variable.type} variable, and connections carry only "
                "Real, Integer, Boolean and Enumeration values. Leave it unconnected, or "
                "expose the information as one of those types in the FMU."
            )
    if TYPE_FAMILY[source.type] != TYPE_FAMILY[target.type]:
        return (
            f"{where}: type mismatch: {origin} is {source.type} but {destination} is "
            f"{target.type}. OMSimulator converts no types; connect Real to Real, Integer to "
            "Integer and Boolean to Boolean, or change a variable's type in its FMU."
        )
    return None


def _unit_problems(
    where: str, origin: str, source: Any, destination: str, target: Any
) -> tuple[list[str], list[str]]:
    """Units that differ are an error; a unit on one side only is a warning."""
    given, expected = _unit_of(source), _unit_of(target)
    if given and expected and given != expected:
        return [
            f"{where}: unit mismatch: {origin} is in '{given}' but {destination} expects "
            f"'{expected}'. OMSimulator converts no units; change the unit in one FMU, or put "
            "a gain component between them."
        ], []
    if given and not expected:
        declared, other, unit = origin, destination, given
    elif expected and not given:
        declared, other, unit = destination, origin, expected
    else:
        return [], []
    return [], [
        f"{where}: {declared} declares unit '{unit}' but {other} declares none, so the value "
        "is passed through unchanged. Check that both mean the same unit."
    ]


def _drivers(index: _Index) -> dict[str, list[tuple[int, str]]]:
    """Input reference -> the (connection number, source) pairs that drive it. Only a connection
    from an existing output to an existing input drives; a broken one is reported once, by
    :func:`_connection_problems`, and doesn't also count as a second driver."""
    drivers: dict[str, list[tuple[int, str]]] = defaultdict(list)
    for i, connection in enumerate(index.loaded.file.connections):
        try:
            source = _variable(index, connection.from_)
            target = _variable(index, connection.to)
        except ValueError:
            continue
        if source.causality == "output" and target.causality == "input":
            drivers[connection.to].append((i, connection.from_))
    return dict(drivers)


def _driver_problems(drivers: Mapping[str, Sequence[tuple[int, str]]]) -> list[str]:
    """An input takes one driver."""
    return [
        f"{ref} has {len(found)} drivers: "
        f"{', '.join(f'connections[{i}] ({origin})' for i, origin in found)}. An input takes "
        "one driver. Keep one connection and delete the others, or add a component that "
        "combines the signals."
        for ref, found in drivers.items()
        if len(found) > 1
    ]


def _parameter_problems(
    index: _Index, drivers: Mapping[str, Sequence[tuple[int, str]]]
) -> list[str]:
    """The system file's parameter values: known, settable and of the right type."""
    errors: list[str] = []
    for name, component in index.loaded.file.components.items():
        for variable, value in component.parameters.items():
            try:
                _checked_value(index, drivers, f"{name}.{variable}", value)
            except ValueError as exc:
                errors.append(f"components.{name}.parameters.{variable}: {exc}")
    return errors


def _unconnected_warnings(
    index: _Index, drivers: Mapping[str, Sequence[tuple[int, str]]]
) -> list[str]:
    """Inputs nothing drives and the system file doesn't set: they keep their FMU start values."""
    warnings: list[str] = []
    for name, component in index.loaded.file.components.items():
        free = [
            variable
            for variable, found in index.variables[name].items()
            if found.causality == "input"
            and f"{name}.{variable}" not in drivers
            and variable not in component.parameters
        ]
        if not free:
            continue
        listed = ", ".join(free[:MAX_LISTED_NAMES])
        if len(free) > MAX_LISTED_NAMES:
            listed += f", and {len(free) - MAX_LISTED_NAMES} more"
        warnings.append(
            f"components.{name}: not connected: {listed}. An unconnected input keeps its FMU "
            "start value; connect it, or set a value in the component's parameters."
        )
    return warnings


def _experiment_problems(experiment: SystemExperiment) -> list[str]:
    start, stop, step = experiment.start_time, experiment.stop_time, experiment.step_size
    return [f"experiment: {problem}" for problem in _timeline_problems(start, stop, step)]


def _timeline_problems(start: float, stop: float, step: float) -> list[str]:
    """What stops OMSimulator from running ``start`` to ``stop`` in steps of ``step`` (all
    finite, ``start < stop``, ``step > 0``): it always starts its clock at 0, takes no step
    larger than the horizon, and steps while ``t < stop - step/2``, so a horizon that is not a
    whole number of steps would end early or late."""
    horizon = stop - start
    problems: list[str] = []
    if start != 0:
        problems.append(
            f"start_time {start:g} can't be used: OMSimulator always starts a system at t = 0. "
            "Use start_time 0 (the default; experiment.start_time in the system file) and "
            "move stop_time instead."
        )
    if step > horizon:
        problems.append(
            f"the step {step:g} s exceeds the horizon {horizon:g} s (stop_time - start_time), "
            "so the run would take no step. Use a step of at most the horizon (output_interval, "
            "or step_size in the system file), or a later stop_time."
        )
    else:
        ratio = horizon / step
        if not math.isclose(ratio, round(ratio), rel_tol=1e-9, abs_tol=1e-9):
            problems.append(_remainder_message(start, horizon, step, ratio))
    return problems


def _remainder_message(start: float, horizon: float, step: float, ratio: float) -> str:
    """A horizon of ``ratio`` steps: the nearest step that divides it, and the stop time that
    the given step reaches."""
    below = math.floor(ratio)
    nearest, count = min(
        ((horizon / n, n) for n in (below, below + 1) if n >= 1),
        key=lambda candidate: abs(candidate[0] - step),
    )
    return (
        f"the horizon {horizon:g} s is {ratio:.6g} steps of {step:g} s, not a whole number, so "
        f"the run would not end at stop_time. Use a step that divides it, such as {nearest:.6g} "
        f"s ({count} steps; output_interval, or step_size in the system file), or end the run "
        f"at stop_time = {start + below * step:.6g}."
    )


def check_system(config: Config, system: str) -> SystemCheck:
    """The ``system_check`` result: :func:`load_system` plus :func:`problems`, cut to
    ``Limits.json_budget_bytes`` (``truncated`` says so).

    Raises:
        UserError: from :func:`load_system` (nothing can be checked).
    """
    loaded = load_system(config, system)
    errors, warnings = problems(loaded, config.limits)
    experiment = loaded.file.experiment
    check = SystemCheck(
        system=relative_path(config, loaded.path),
        ok=not errors,
        components={name: relative_path(config, path) for name, path in loaded.fmus.items()},
        connections=len(loaded.file.connections),
        experiment=SystemExperimentView(
            start_time=experiment.start_time,
            stop_time=experiment.stop_time,
            step_size=experiment.step_size,
        ),
        errors=errors,
        warnings=warnings,
    )
    return budget.fit_to_budget(check, config.limits.json_budget_bytes, _fewer_problems)


def _fewer_problems(check: SystemCheck) -> SystemCheck | None:
    """Three quarters of the warnings, then of the errors; ``ok`` keeps its value."""
    if check.warnings:
        keep = len(check.warnings) * 3 // 4
        return check.model_copy(update={"warnings": check.warnings[:keep], "truncated": True})
    count = len(check.errors)
    if count <= 1:
        return None
    return check.model_copy(update={"errors": check.errors[: count * 3 // 4], "truncated": True})


# --- parameter layers -------------------------------------------------------------------------


def resolve_parameters(
    loaded: LoadedSystem,
    paramset: Paramset | None,
    start_values: Mapping[str, StartValue] | None,
) -> dict[str, ResolvedValue]:
    """Merge the parameter layers into ``SystemSpec.parameters``, keyed
    ``<component>.<variable>`` in sorted order: system file < ``paramset`` < ``start_values``.

    Every name is checked as in :func:`problems` (exists, settable, type, not a driven input);
    a paramset unit that differs from the declared unit is refused. Each value is converted to
    its variable's type.

    Raises:
        UserError: the first bad name or value, naming its layer and the fix.
    """
    index = _Index.of(loaded)
    drivers = _drivers(index)
    system_values = {
        f"{name}.{variable}": value
        for name, component in loaded.file.components.items()
        for variable, value in component.parameters.items()
    }
    layers: list[tuple[ParameterLayer, Mapping[str, StartValue], Mapping[str, str]]] = [
        ("system", system_values, {}),
        ("paramset", {}, {}) if paramset is None else ("paramset", paramset.values, paramset.units),
        ("start_values", start_values or {}, {}),
    ]
    merged: dict[str, ResolvedValue] = {}
    for layer, values, units in layers:
        for ref, value in values.items():
            try:
                coerced = _checked_value(index, drivers, ref, value, units.get(ref))
            except ValueError as exc:
                raise UserError(f"{LAYER_LABELS[layer]} {ref!r}: {exc}") from exc
            merged[ref] = ResolvedValue(value=coerced, source=layer)
    return dict(sorted(merged.items()))


def _checked_value(
    index: _Index,
    drivers: Mapping[str, Sequence[tuple[int, str]]],
    ref: str,
    value: StartValue,
    unit: str | None = None,
) -> StartValue:
    """``value`` for ``ref`` converted to the variable's type.

    Raises:
        ValueError: ``ref`` names nothing, isn't settable, the value doesn't fit the type or its
            unit differs from the declared one; the text has the fix.
    """
    variable = _variable(index, ref)
    driven = drivers.get(ref)
    problem = _unsettable(ref, variable, None if not driven else driven[0][1])
    if problem is not None:
        raise ValueError(problem)
    coerced = _coerced(variable, value)
    if coerced is None:
        raise ValueError(_type_message(ref, variable, value))
    declared = _unit_of(variable)
    if unit and declared and unit != declared:
        raise ValueError(
            f"the parameter set gives {ref} in '{unit}' but the FMU declares '{declared}'. "
            "Agentic FMI converts no units; convert the value and change the unit in the .ssv."
        )
    return coerced


def _unsettable(ref: str, variable: Any, driver: str | None) -> str | None:
    """Why ``variable`` can't be set before initialization, or ``None``: only parameters,
    inputs no connection drives, and states with initial exact or approx can."""
    causality = variable.causality
    if causality == "output":
        return (
            f"{ref} is an output, which the FMU computes. Set a parameter or an unconnected "
            "input instead."
        )
    if causality == "calculatedParameter":
        return (
            f"{ref} is a calculated parameter, derived from other parameters. Set those "
            "parameters instead."
        )
    if causality == "structuralParameter":
        return (
            f"{ref} is a structural parameter, which changes the model's structure and isn't "
            "set here. Set an ordinary parameter."
        )
    if causality == "independent":
        return f"{ref} is the independent variable (time) and can't be set."
    if variable.variability == "constant":
        return f"{ref} is constant and can't be changed."
    if causality == "input":
        if driver is None:
            return None
        return (
            f"{ref} is an input driven by {driver}, so the connection supplies its value. "
            "Remove the value, or delete the connection."
        )
    if causality == "parameter" or variable.initial in ("exact", "approx"):
        return None
    return (
        f"{ref} is a {causality} variable the FMU computes (initial={variable.initial}). Only "
        "parameters, unconnected inputs and states with initial exact or approx can be set; "
        "fmu_variables with causality='parameter' lists the parameters."
    )


def _coerced(variable: Any, value: StartValue) -> StartValue | None:
    """``value`` as the variable's type (Real ``float``, Integer and Enumeration ``int``,
    Boolean ``bool``, String ``str``), or ``None`` if it doesn't fit."""
    if variable.type == "String":
        return value if isinstance(value, str) else None
    family = TYPE_FAMILY.get(variable.type)
    if isinstance(value, bool):
        return value if family == "boolean" else None
    if isinstance(value, str):
        return None
    if family in ("integer", "enumeration"):
        if isinstance(value, int):
            return value
        return int(value) if value.is_integer() else None
    if family == "float":
        try:
            number = float(value)
        except OverflowError:
            return None
        return number if math.isfinite(number) else None
    return None


def _type_message(ref: str, variable: Any, value: StartValue) -> str:
    expected = EXPECTED_VALUE.get(TYPE_FAMILY.get(variable.type, variable.type))
    if expected is None:
        return (
            f"{ref} is a {variable.type} variable, which can't be set. Set a Real, Integer, "
            "Boolean, Enumeration or String variable."
        )
    return (
        f"{ref} is a {variable.type} variable and needs {expected}, but the value is "
        f"{value!r}. Pass {expected}."
    )


# --- the run plan -----------------------------------------------------------------------------


def default_outputs(loaded: LoadedSystem, limits: Limits) -> list[str]:
    """Every component's recordable outputs as ``<component>.<variable>``, in system-file
    order, then each FMU's variable order; at most ``Limits.page_max``."""
    refs = [
        f"{name}.{variable.name}"
        for name in loaded.file.components
        for variable in loaded.descriptions[name].modelVariables
        if variable.causality == "output"
        and variable.type in TYPE_FAMILY
        and not variable.dimensions
    ]
    return refs[: limits.page_max]


def plan_run(
    config: Config,
    loaded: LoadedSystem,
    *,
    paramset: Paramset | None = None,
    start_values: Mapping[str, StartValue] | None = None,
    outputs: Sequence[str] | None = None,
    start_time: float | None = None,
    stop_time: float | None = None,
    step_size: float | None = None,
    timeout_s: float,
    force: bool = False,
    omsimulator: OmsVersion,
    live: bool = False,
) -> SystemPlan:
    """Validate a system run request: no :func:`problems` errors (else the first few, with
    "call system_check for all"); the experiment with overrides (``step_size`` comes from
    ``run_start``'s ``output_interval``), which must start at 0 and be a whole number of
    steps (``_timeline_problems``); communication steps above
    ``Limits.max_internal_steps`` refused unless ``force``; parameters resolved; outputs
    checked (``<component>.<variable>``, recordable, close matches) or defaulted, and a result
    table (steps x recorded columns) above ``Limits.system_max_cells`` refused unless ``force``.
    ``omsimulator`` is the installed identity the caller verified against the pin; the spec
    records it. ``live`` (ADR 0010) makes a live run: the spec records ``live`` and
    ``idle_limit_s = Timing.live_idle_limit_s``; the checks are the same (every component is
    Co-Simulation already).

    Raises:
        UserError: any refusal, with the fix.
    """
    limits = config.limits
    errors, _ = _structure_problems(loaded)
    if errors:
        raise UserError(_refusal(loaded.name, _clipped(errors, limits)))
    start, stop, step = _effective_experiment(
        loaded.name, loaded.file.experiment, start_time, stop_time, step_size
    )
    steps = (stop - start) / step
    if steps > limits.max_internal_steps and not force:
        raise UserError(
            f"Refusing to start {loaded.name}: {steps:.3g} communication steps "
            f"({stop - start:g} s at h = {step:g} s), above the limit of "
            f"{limits.max_internal_steps:.3g}. Options: raise output_interval (the step "
            "changes a loop's dynamics, so check the result); shorten stop_time; or pass "
            "force=true with a timeout_s."
        )
    recorded = _checked_outputs(loaded, outputs, limits)
    if not force:
        _check_result_size(loaded.name, steps, step, len(recorded), limits)
    return SystemPlan(
        loaded=loaded,
        paramset=None if paramset is None else paramset.ref,
        parameters=resolve_parameters(loaded, paramset, start_values),
        start_time=start,
        stop_time=stop,
        step_size=step,
        outputs=recorded,
        timeout_s=timeout_s,
        estimated_steps=steps,
        force=force,
        fmu_refs=_fmu_refs(loaded),
        omsimulator=omsimulator,
        live=live,
        idle_limit_s=config.timing.live_idle_limit_s if live else None,
    )


def _check_result_size(name: str, steps: float, step: float, outputs: int, limits: Limits) -> None:
    """Refuse a run whose table (one row per communication step plus row 0, ``time`` and the
    ``outputs`` as columns) would exceed ``Limits.system_max_cells``: ``result.csv`` and the
    worker's memory both grow with it."""
    rows, columns = steps + 1, outputs + 1
    cells = rows * columns
    if cells <= limits.system_max_cells:
        return
    raise UserError(
        f"Refusing to start {name}: the result would hold {rows:,.0f} rows x {columns} columns "
        f"= {cells:,.0f} values ({steps * step:g} s at h = {step:g} s, one row per step; about "
        f"{cells * CSV_BYTES_PER_CELL / 1e6:,.1f} MB of result.csv), above the limit of "
        f"{limits.system_max_cells:,.0f}. Options: raise output_interval (the step changes a "
        "loop's dynamics, so check the result); record fewer outputs "
        "(outputs=['<component>.<variable>', ...]); shorten stop_time; or pass force=true with a "
        "timeout_s."
    )


def _refusal(name: str, errors: Sequence[str]) -> str:
    """The first few problems of a system that can't run, and where to see all of them."""
    quoted = " ".join(
        f"({i}) {truncate(error, MAX_REFUSAL_CHARS)}"
        for i, error in enumerate(errors[:MAX_REFUSAL_ERRORS], start=1)
    )
    return (
        f"Can't run {name}: it has {len(errors)} error(s). {quoted} Call system_check for all "
        "of them, fix the system file, then call run_start again."
    )


def _effective_experiment(
    name: str,
    experiment: SystemExperiment,
    start_time: float | None,
    stop_time: float | None,
    step_size: float | None,
) -> tuple[float, float, float]:
    """The system file's experiment with the run's overrides: ``(start, stop, step)``."""
    start = experiment.start_time if start_time is None else start_time
    stop = experiment.stop_time if stop_time is None else stop_time
    step = experiment.step_size if step_size is None else step_size
    if not (math.isfinite(start) and math.isfinite(stop)) or stop <= start:
        raise UserError(
            f"stop_time ({stop:g}) must be greater than start_time ({start:g}). Pass a "
            "stop_time after the start."
        )
    if not math.isfinite(step) or step <= 0:
        raise UserError(
            f"The communication step must be a positive number (got {step:g}). Pass a positive "
            "output_interval, or fix experiment.step_size in the system file."
        )
    problems = _timeline_problems(start, stop, step)
    if problems:
        raise UserError(f"Can't run {name}: {problems[0]}")
    return start, stop, step


def _checked_outputs(
    loaded: LoadedSystem, outputs: Sequence[str] | None, limits: Limits
) -> list[str]:
    """The variables to record: the caller's (checked) or every component's outputs."""
    if not outputs:
        defaults = default_outputs(loaded, limits)
        if not defaults:
            raise UserError(
                f"No component of {loaded.name} declares a recordable output. Pass "
                "outputs=['<component>.<variable>', ...] naming the variables to record "
                "(fmu_variables lists each FMU's)."
            )
        return defaults
    names = [name for name in dict.fromkeys(outputs) if name != TIME_COLUMN]
    if not names:
        raise UserError("outputs names only 'time', which is always recorded. Name a variable.")
    index = _Index.of(loaded)
    for ref in names:
        try:
            variable = _variable(index, ref)
        except ValueError as exc:
            raise UserError(
                f"outputs entry {ref!r}: {exc} Name outputs as <component>.<variable>."
            ) from exc
        if variable.type not in TYPE_FAMILY:
            raise UserError(
                f"Output {ref!r} is a {variable.type} variable; only numeric, Boolean and "
                "enumeration variables can be recorded. Choose other outputs "
                "(fmu_variables shows each type)."
            )
    return names


def _fmu_refs(loaded: LoadedSystem) -> dict[str, FmuRef]:
    """Each component's FMU pinned by sha256; a file used by several components is hashed once."""
    refs: dict[Path, FmuRef] = {}
    for path, names in _components_by_path(loaded).items():
        refs[path] = _fmu_ref(names[0], path, loaded.descriptions[names[0]])
    return {name: refs[path] for name, path in loaded.fmus.items()}


def _fmu_ref(component: str, path: Path, md: ModelDescription) -> FmuRef:
    try:
        return FmuRef(
            path=str(path),
            sha256=sha256_file(path),
            size_bytes=path.stat().st_size,
            fmi_version=md.fmiVersion,
            model_name=md.modelName,
        )
    except OSError as exc:
        raise UserError(
            f"components.{component}: can't read {path.name}: {exc.strerror or exc}. Check "
            "that the file is still there and readable."
        ) from exc
    except ValidationError as exc:
        raise UserError(
            f"components.{component}: {path.name} declares FMI version {md.fmiVersion!r}; "
            "Agentic FMI runs FMI 2.0 and 3.0 FMUs. Export the model as one of those."
        ) from exc


def system_file_schema() -> dict[str, Any]:
    """The JSON Schema of :class:`SystemFile` (validation mode, aliases), as committed."""
    schema = SystemFile.model_json_schema(mode="validation", by_alias=True)
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}


def export_system_file_schema(directory: Path) -> Path:
    """Write :data:`SYSTEM_SCHEMA_FILE` into ``directory`` deterministically (2-space indent,
    LF, trailing newline) and return its path. Regenerate the committed copy with
    ``uv run python -c "from pathlib import Path; from agentic_fmi.system import
    export_system_file_schema; export_system_file_schema(Path('docs/schemas'))"``."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / SYSTEM_SCHEMA_FILE
    text = json.dumps(system_file_schema(), indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path
